// Smooth outline silhouettes (Catmull-Rom splines through anatomical landmark points).
function spline(pts, closed = true, t = 0.5) {
  const n = pts.length, P = (i) => pts[(i + n) % n];
  let d = `M${pts[0][0]} ${pts[0][1]}`;
  const last = closed ? n : n - 1;
  for (let i = 0; i < last; i++) {
    const p0 = closed || i > 0 ? P(i - 1) : P(i), p1 = P(i), p2 = P(i + 1), p3 = closed || i + 2 < n ? P(i + 2) : P(i + 1);
    const c1 = [p1[0] + (p2[0] - p0[0]) * t / 3, p1[1] + (p2[1] - p0[1]) * t / 3];
    const c2 = [p2[0] - (p3[0] - p1[0]) * t / 3, p2[1] - (p3[1] - p1[1]) * t / 3];
    d += ` C${c1.map((v) => v.toFixed(1)).join(" ")} ${c2.map((v) => v.toFixed(1)).join(" ")} ${p2[0]} ${p2[1]}`;
  }
  return d + (closed ? " Z" : "");
}
const path = (pts, t) => `<path d="${spline(pts, true, t)}"/>`;

